import { it, expect, afterAll } from 'vitest';
import { run, generate } from '../src/index.js';
import { existsSync, readFileSync, readdirSync, rmSync, cpSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const directory = join(import.meta.dirname, 'fixtures/path-collisions');
const output = join(import.meta.dirname, '../.test-output-collisions');
afterAll(() => rmSync(output, { recursive: true, force: true }));
it('keeps specializations, case-only names and reserved root names distinct, with working links', async () => {
  await run({ directory, classes: true, output: join(output, '%s.md'), quiet: true, frontmatter: true });
  const names = readdirSync(output);
  expect(names).toHaveLength(7); // six types and root index
  expect(new Set(names.map(n => n.toLowerCase())).size).toBe(7);
  expect(names).toContain('Plain.md'); // unrelated URLs do not change
  expect(readFileSync(join(output, 'api.md'), 'utf8')).toContain('Generated by');
  const pages = await generate({ directory, quiet: true });
  expect(pages).toHaveLength(6);
  expect(new Set(pages.map(p => p.slug.toLowerCase())).size).toBe(6);
  for (const page of pages) {
    expect(names).toContain(`${page.slug}.md`);
    expect(existsSync(join(output, `${page.slug}.md`))).toBe(true);
    for (const [, target] of page.markdown.matchAll(/\]\(([^)#]+)\.html#/g)) {
      expect(pages.some(p => p.slug === target), `target ${target}`).toBe(true);
    }
  }
  for (const name of names) {
    for (const [, target] of readFileSync(join(output, name), 'utf8').matchAll(/\]\(([^)#]+\.md)#/g)) {
      expect(names).toContain(target);
    }
  }
  const pointer = pages.find(p => p.markdown.includes('POINTER_SPECIALIZATION.'))!;
  const reference = pages.find(p => p.markdown.includes('REFERENCE_SPECIALIZATION.'))!;
  expect(pointer.slug).not.toBe(reference.slug);
  expect(pointer.markdown).toContain(`](${reference.slug}.html#`);
  expect(reference.markdown).toContain(`](${pointer.slug}.html#`);
});

it('does not reserve an index filename when no index is emitted', async () => {
  const destination = join(output, 'no-index');
  await run({ directory, classes: true, noindex: true, output: join(destination, '%s.md'), quiet: true });
  expect(readdirSync(destination)).toContain('api.md');
  expect((await generate({ directory, quiet: true })).some(page => page.slug === 'api')).toBe(true);
});

it('keeps the requested single-file output name', async () => {
  const destination = join(output, 'single.md');
  await run({ directory, output: destination, quiet: true });
  expect(existsSync(destination)).toBe(true);
});

it('allocates the same names after index reordering, without frontmatter or a root index', async () => {
  const reversed = join(output, 'xml');
  cpSync(directory, reversed, { recursive: true });
  const index = readFileSync(join(reversed, 'index.xml'), 'utf8');
  const entries = [...index.matchAll(/<compound[\s\S]*?<\/compound>/g)].map(m => m[0]);
  writeFileSync(join(reversed, 'index.xml'), `<doxygenindex>${entries.reverse().join('')}</doxygenindex>`);
  const original = await generate({ directory, quiet: true });
  const reordered = await generate({ directory: reversed, quiet: true });
  expect(reordered.map(p => p.slug).sort()).toEqual(original.map(p => p.slug).sort());
  const destination = join(output, 'reordered');
  await run({ directory: reversed, output: join(destination, '%s.md'), classes: true, noindex: true, quiet: true });
  expect(readdirSync(destination).sort()).toEqual(original.map(p => `${p.slug}.md`).sort());
});
