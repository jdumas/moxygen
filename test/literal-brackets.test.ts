import { it, expect, afterAll } from 'vitest';
import { generate, run } from '../src/index.js';
import { readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
const directory = join(import.meta.dirname, 'fixtures/literal-brackets');
const output = join(import.meta.dirname, '../.test-output-brackets');
afterAll(() => rmSync(output, { recursive: true, force: true }));
it('escapes XML prose, not generated links, code, formulas or declarations', async () => {
  const [page] = await generate({ directory, quiet: true });
  const text = page.markdown;
  expect(text).toContain('Use x\\[i\\](0) and lambdas \\[\\](Index,Index) in prose.');
  expect(text).toContain('array\\[3\\](1)');
  expect(text).toContain('C:\\\\tmp');
  expect(text).toContain('`x[i](0)`');
  expect(text).toContain('[`x[i](0)`](#apply)');
  expect(text).toContain('[help](https://example.org/help)');
  expect(text).toContain('[array \\[index](https://example.org/array)');
  expect(text).toContain('[array \\[index](#apply)');
  expect(text).toContain('```cpp\nx[i](0); [](Index,Index) {};\n```');
  expect(text).toContain('```\narray[3](1)\n```');
  expect(text).toContain('<pre>array[3](1)</pre>');
  expect(text).toContain('$x[i](0)$');
  expect(text).toContain('Use values\\[3\\](1).');
  expect(text).toContain('values[3]');
  await run({ directory, output: join(output, '%s.md'), classes: true, quiet: true });
  expect(readFileSync(join(output, 'Samples.md'), 'utf8')).toContain('x\\[i\\](0)');
});
